"""Generate the Gazebo warehouse world from the CPU simulator's geometry.

The CPU simulator (turtlebot_nav.simulation.WAREHOUSE) is the single source of
obstacle positions and sizes, so a policy trained on the CPU backend sees the
same layout in Gazebo. tests/test_core.py fails if the checked-in world drifts.

    python scripts/generate_world.py            # rewrite the world file
    python scripts/generate_world.py --check    # exit 1 if it is out of date
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from turtlebot_nav.simulation import WAREHOUSE

WORLD_FILE = Path(__file__).resolve().parents[1]/'src'/'turtlebot3_smart_nav'/'worlds'/'warehouse.world'
WALL_T, WALL_H = 0.10, 0.60
RACK_H, PALLET_H, BARREL_H, COLUMN_H = 1.60, 0.70, 0.90, 2.50


def static_box(name, x, y, sx, sy, sz, material):
    return (f'  <model name="{name}"><static>true</static><pose>{x:.3f} {y:.3f} {sz/2:.3f} 0 0 0</pose><link name="body">\n'
            f'    <collision name="c"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>\n'
            f'    <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>'
            f'<material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>{material}</name></script></material></visual>\n'
            '  </link></model>\n')


def static_cylinder(name, x, y, r, h, material):
    return (f'  <model name="{name}"><static>true</static><pose>{x:.3f} {y:.3f} {h/2:.3f} 0 0 0</pose><link name="body">\n'
            f'    <collision name="c"><geometry><cylinder><radius>{r:.3f}</radius><length>{h:.3f}</length></cylinder></geometry></collision>\n'
            f'    <visual name="v"><geometry><cylinder><radius>{r:.3f}</radius><length>{h:.3f}</length></cylinder></geometry>'
            f'<material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>{material}</name></script></material></visual>\n'
            '  </link></model>\n')


def world_sdf(world=WAREHOUSE):
    hx, hy = world.half_x, world.half_y
    parts = ['<?xml version="1.0"?>\n',
             '<!-- Generated by scripts/generate_world.py from turtlebot_nav.simulation.WAREHOUSE. Do not edit. -->\n',
             '<sdf version="1.6"><world name="warehouse">\n',
             '  <physics type="ode"><max_step_size>0.001</max_step_size><real_time_update_rate>1000</real_time_update_rate></physics>\n',
             '  <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.75 0.8 0.85 1</background><shadows>false</shadows></scene>\n',
             '  <light name="sun" type="directional"><cast_shadows>false</cast_shadows><direction>-0.4 0.2 -0.9</direction>'
             '<diffuse>0.9 0.9 0.9 1</diffuse></light>\n',
             '  <model name="floor"><static>true</static><link name="floor">\n'
             '    <collision name="c"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry></collision>\n'
             '    <visual name="v"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>'
             '<material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>Gazebo/Grey</name></script></material></visual>\n'
             '  </link></model>\n']
    # Wall inner faces sit exactly on the simulator bounds.
    for name, x, y, sx, sy in [('wall_north', 0, hy+WALL_T/2, 2*hx+2*WALL_T, WALL_T),
                               ('wall_south', 0, -hy-WALL_T/2, 2*hx+2*WALL_T, WALL_T),
                               ('wall_east', hx+WALL_T/2, 0, WALL_T, 2*hy),
                               ('wall_west', -hx-WALL_T/2, 0, WALL_T, 2*hy)]:
        parts.append(static_box(name, x, y, sx, sy, WALL_H, 'Gazebo/DarkGrey'))
    for i, (cx, cy, bx, by) in enumerate(world.boxes):
        if bx >= 1.0:
            parts.append(static_box(f'rack_{i}', cx, cy, 2*bx, 2*by, RACK_H, 'Gazebo/Orange'))
        elif bx <= 0.2 and by <= 0.2:
            parts.append(static_box(f'column_{i}', cx, cy, 2*bx, 2*by, COLUMN_H, 'Gazebo/Yellow'))
        else:
            parts.append(static_box(f'pallet_{i}', cx, cy, 2*bx, 2*by, PALLET_H, 'Gazebo/Wood'))
    for i, (cx, cy, r) in enumerate(world.circles):
        parts.append(static_cylinder(f'barrel_{i}', cx, cy, r, BARREL_H, 'Gazebo/Blue'))
    # Goal marker: visual only (no collision, so the LiDAR never sees it); the ROS adapter moves it each episode.
    parts.append('  <model name="goal_marker"><pose>0 0 0.01 0 0 0</pose><link name="marker"><gravity>false</gravity><kinematic>true</kinematic>\n'
                 '    <visual name="disc"><geometry><cylinder><radius>0.20</radius><length>0.02</length></cylinder></geometry>'
                 '<material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>Gazebo/GreenTransparent</name></script></material></visual>\n'
                 '    <visual name="pole"><pose>0 0 0.30 0 0 0</pose><geometry><cylinder><radius>0.02</radius><length>0.60</length></cylinder></geometry>'
                 '<material><script><uri>file://media/materials/scripts/gazebo.material</uri><name>Gazebo/Green</name></script></material></visual>\n'
                 '  </link></model>\n')
    parts.append('  <gui><camera name="user_camera"><pose>0 -8.2 8.4 0 0.86 1.5708</pose></camera></gui>\n')
    parts.append('</world></sdf>\n')
    return ''.join(parts)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail if the checked-in world is out of date')
    args = parser.parse_args(argv)
    text = world_sdf()
    if args.check:
        if not WORLD_FILE.exists() or WORLD_FILE.read_text(encoding='utf-8') != text:
            print('warehouse.world is out of date; run scripts/generate_world.py', file=sys.stderr)
            return 1
        return 0
    WORLD_FILE.write_text(text, encoding='utf-8')
    print('wrote', WORLD_FILE)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
